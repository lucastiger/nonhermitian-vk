"""The ``(V, G)`` profiles used in the paper.

Each function evaluates a potential/gain-loss pair on a grid ``x`` produced by
:func:`nhvk.core.make_grid` and returns ``(V, G)``.  The gain-loss profile is
returned with its physical amplitude already applied, so a :class:`nhvk.core.Model`
built from these arrays is used at ``eps = 1``; passing the unit amplitude and
continuing in ``eps`` from ``0`` to ``A`` is the equivalent route taken by the
scripts that need a Hermitian anchor.
"""

from __future__ import annotations

import numpy as np

__all__ = ["wadati_gaussian", "wadati_shifted", "wadati_even",
           "pt_well", "pt_barrier"]


def wadati_gaussian(x: np.ndarray, A: float) -> tuple[np.ndarray, np.ndarray]:
    """Theorem A profile: the Wadati pair generated by ``g = A x exp(-x^2/2)``.

    Returns ``V = -g^2`` and ``G = g' = A (1 - x^2) exp(-x^2/2)``, so that the
    linear part is Wadati-factorisable,
    ``-d_xx - g^2 + i g' = (d_x + i g)(-d_x + i g)``.

    Two properties of ``g`` matter for the paper's construction.  ``g`` is
    **odd**, so ``G = g'`` is **even**; since a PT-symmetric configuration needs
    ``G`` odd, this branch is genuinely non-PT-symmetric, which is the point of
    Theorem A.  And ``g`` is **non-monotone**, so ``G`` changes sign -- Lemma P
    forbids a sign-definite ``G``, because any decaying stationary state must
    satisfy ``int G |phi|^2 dx = 0``.

    Parameters
    ----------
    x : ndarray
        Grid points.
    A : float
        Amplitude of ``g``.  The paper uses ``A = 1``.

    Returns
    -------
    V, G : ndarray
        Potential and gain-loss profile on ``x``.
    """
    g = A*x*np.exp(-x**2/2)
    gp = A*(1-x**2)*np.exp(-x**2/2)
    return -g**2, gp


def wadati_shifted(x: np.ndarray, A: float, c: float = 0.6) -> tuple[np.ndarray, np.ndarray]:
    """Wadati pair generated by ``g = A (x + c) exp(-x^2/2)``, with ``c != 0``.

    Returns ``V = -g^2`` and ``G = g' = A (1 - x(x+c)) exp(-x^2/2)``.  This is
    the decisive control of Section ``sec:quartet``: ``g`` is **not odd**, so
    neither ``V`` nor ``G`` is even and no parity operator exists at all, yet
    the invariance ``lambda -> conj(lambda)`` still holds to ``~4e-13``.  Every
    explanation of the quartet routed through parity is excluded by it.  The
    paper uses ``c = 0.6``.
    """
    e = np.exp(-x**2/2)
    return -(A*(x + c)*e)**2, A*(1 - x*(x + c))*e


def wadati_even(x: np.ndarray, A: float) -> tuple[np.ndarray, np.ndarray]:
    """Wadati pair generated by the **even** ``g = A exp(-x^2/2)``.

    Returns ``V = -g^2`` (even) and ``G = g' = -A x exp(-x^2/2)`` (**odd**), so
    this configuration *is* PT-symmetric and Corollary ``cor:symB`` applies to
    it by proof.  It is the positive control for the quartet test of
    Section ``sec:quartet``.
    """
    e = np.exp(-x**2/2)
    return -(A*e)**2, -A*x*e


def pt_well(x: np.ndarray, V0: float, A: float) -> tuple[np.ndarray, np.ndarray]:
    """Appendix F Configuration I: PT-symmetric sech-squared well.

    Returns ``V = -V0 sech^2(x)`` (even) and ``G = A sech(x) tanh(x)`` (odd), so
    the configuration is PT-symmetric.  The paper uses ``V0 = 2``, for which the
    linear operator ``-d_xx - 2 sech^2(x)`` has its bound state at ``E = -1`` and
    the focusing soliton family lives at ``omega < -1``.

    Parameters
    ----------
    x : ndarray
        Grid points.
    V0 : float
        Depth of the well.
    A : float
        Amplitude of the gain-loss profile.

    Returns
    -------
    V, G : ndarray
        Potential and gain-loss profile on ``x``.
    """
    V = -V0/np.cosh(x)**2
    G = A*np.tanh(x)/np.cosh(x)
    return V, G


def pt_barrier(x: np.ndarray, V0: float, A: float) -> tuple[np.ndarray, np.ndarray]:
    """Sections 3.7 and 5.3: PT-symmetric sech-squared barrier.

    Returns ``V = +V0 sech^2(x)`` (even) and ``G = -A sech(x) tanh(x)`` (odd).
    The paper uses ``V0 = 0.3``.

    Note that ``V`` here is a **repulsive barrier**, not a well: the linear
    operator ``-d_xx + V0 sech^2(x)`` has no bound state, so there is no linear
    eigenvalue to bifurcate from and the focusing soliton family exists for all
    ``omega < 0``.  That is what makes this base usable at frequencies as far
    apart as ``omega = -0.8`` and ``omega = -2.5``.

    Parameters
    ----------
    x : ndarray
        Grid points.
    V0 : float
        Height of the barrier.
    A : float
        Amplitude of the gain-loss profile.

    Returns
    -------
    V, G : ndarray
        Potential and gain-loss profile on ``x``.
    """
    V = V0/np.cosh(x)**2
    G = -A*np.tanh(x)/np.cosh(x)
    return V, G
